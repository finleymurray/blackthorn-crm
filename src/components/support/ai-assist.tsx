"use client";

import * as React from "react";
import { useRouter } from "next/navigation";
import { Sparkles, FileText, Wand2, ListChecks } from "lucide-react";
import { Button } from "@/components/ui/button";
import { DropdownMenu, DropdownMenuContent, DropdownMenuItem, DropdownMenuLabel, DropdownMenuTrigger } from "@/components/ui/dropdown-menu";
import { Dialog, DialogContent, DialogDescription, DialogFooter, DialogHeader, DialogTitle } from "@/components/ui/dialog";
import { useToast } from "@/components/ui/toast";
import { aiDraftReply, aiSummarise, aiTriage } from "@/app/(app)/support/ai-actions";

/** Only rendered when ANTHROPIC_API_KEY is configured. Every output is a suggestion the staff member reviews. */
export function AiAssist({ ticketId, onDraft }: { ticketId: string; onDraft: (text: string) => void }) {
  const router = useRouter();
  const { toast } = useToast();
  const [pending, start] = React.useTransition();
  const [summary, setSummary] = React.useState<string | null>(null);
  const [triage, setTriage] = React.useState<{ category: string; priority: string; reason: string } | null>(null);

  return (
    <>
      <DropdownMenu>
        <DropdownMenuTrigger asChild>
          <Button type="button" variant="ghost" size="sm" loading={pending} className="text-accent-text">
            <Sparkles /> AI assist
          </Button>
        </DropdownMenuTrigger>
        <DropdownMenuContent align="start" className="w-64">
          <DropdownMenuLabel>Suggestions you review before anything is sent</DropdownMenuLabel>
          <DropdownMenuItem
            onSelect={() =>
              start(async () => {
                const r = await aiDraftReply(ticketId);
                if (!r.ok) toast({ kind: "error", title: "AI draft failed", description: r.error });
                else onDraft((r.data as { text: string }).text);
              })
            }
          >
            <Wand2 /> Draft a reply
          </DropdownMenuItem>
          <DropdownMenuItem
            onSelect={() =>
              start(async () => {
                const r = await aiSummarise(ticketId);
                if (!r.ok) toast({ kind: "error", title: "AI summary failed", description: r.error });
                else setSummary((r.data as { text: string }).text);
              })
            }
          >
            <FileText /> Summarise the thread
          </DropdownMenuItem>
          <DropdownMenuItem
            onSelect={() =>
              start(async () => {
                const r = await aiTriage(ticketId);
                if (!r.ok) toast({ kind: "error", title: "AI triage failed", description: r.error });
                else setTriage(r.data as { category: string; priority: string; reason: string });
              })
            }
          >
            <ListChecks /> Suggest category and priority
          </DropdownMenuItem>
        </DropdownMenuContent>
      </DropdownMenu>

      {summary ? (
        <Dialog open onOpenChange={(o) => !o && setSummary(null)}>
          <DialogContent size="md">
            <DialogHeader>
              <DialogTitle>Thread summary</DialogTitle>
              <DialogDescription>Generated by Claude from the messages on this ticket.</DialogDescription>
            </DialogHeader>
            <div className="whitespace-pre-wrap rounded-md bg-white/[0.04] px-3 py-2 text-sm leading-relaxed">{summary}</div>
            <DialogFooter>
              <Button type="button" variant="secondary" onClick={() => setSummary(null)}>
                Close
              </Button>
            </DialogFooter>
          </DialogContent>
        </Dialog>
      ) : null}

      {triage ? (
        <Dialog open onOpenChange={(o) => !o && setTriage(null)}>
          <DialogContent size="sm">
            <DialogHeader>
              <DialogTitle>Suggested triage</DialogTitle>
              <DialogDescription>{triage.reason}</DialogDescription>
            </DialogHeader>
            <dl className="grid grid-cols-2 gap-2 text-sm">
              <div className="rounded-md bg-white/[0.04] p-2">
                <dt className="text-xs text-muted">Category</dt>
                <dd className="font-medium">{triage.category.replace(/_/g, " ")}</dd>
              </div>
              <div className="rounded-md bg-white/[0.04] p-2">
                <dt className="text-xs text-muted">Priority</dt>
                <dd className="font-medium">{triage.priority}</dd>
              </div>
            </dl>
            <DialogFooter>
              <Button type="button" variant="ghost" onClick={() => setTriage(null)}>
                Ignore
              </Button>
              <Button
                type="button"
                loading={pending}
                onClick={() =>
                  start(async () => {
                    const { updateTicket } = await import("@/app/(app)/support/actions");
                    const r = await updateTicket(ticketId, { category: triage.category, priority: triage.priority });
                    if (!r.ok) toast({ kind: "error", title: "Not applied", description: r.error });
                    else {
                      toast({ kind: "success", title: "Triage applied" });
                      setTriage(null);
                      router.refresh();
                    }
                  })
                }
              >
                Apply
              </Button>
            </DialogFooter>
          </DialogContent>
        </Dialog>
      ) : null}
    </>
  );
}
